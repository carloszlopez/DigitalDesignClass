// Enable
////////////////////////////////////////////////////////////////////////////////
    // enable
    always @(posedge clk) begin
        if (enable) begin
            q <= d;
        end
    end

    // reset & enable
    always @(posedge clk or posedge reset) begin
        if (reset) begin
            q <= 0;
        end
        else if (enable) begin
            q <= d;
        end
    end